#!/usr/bin/env python3
"""Generate the PlainSpeak polygonal spinning donut engine.

The generated program computes an animated torus in native PlainSpeak prose
(loops, variables, and the built-in "sine of" / "cosine of" forms) and streams
the donut_host token protocol to stdout through the imported C printf:

    F                              begin frame
    P x1 y1 ... x4 y4 r g b        shaded quad (any whitespace separates)
    S                              swap/present

Run:

    python3 scripts/gen_donut_engine.py                 # examples/donut_engine.eng (infinite)
    python3 scripts/gen_donut_engine.py --frames 3     # examples/donut_engine_finite.eng

Then:

    ./build/plainspeak examples/donut_engine.eng -o /tmp/donut
    /tmp/donut | ./host/donut_host
"""

import argparse
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

R, TUBE = 3.0, 1.25
RING, TUBE_N = 16, 10
SCALE, OX, OY = 28.0, 120.0, 120.0
SPIN_STEP = 0.05
TILT = 0.72
LIGHT = (0.32, 0.58, 0.75)
TH_STEP = 2 * math.pi / RING
PH_STEP = 2 * math.pi / TUBE_N
CB, SB = round(math.cos(TILT), 12), round(math.sin(TILT), 12)


def num(v):
    return "{:.12g}".format(float(v))


def generate(frames):
    L = []

    def sent(text):
        L.append(text)

    sent("(A live polygonal spinning torus, written in native PlainSpeak.)")
    sent("(Generated by scripts/gen_donut_engine.py; do not edit by hand.)")
    sent(
        "(It streams a shaded-quad token protocol on stdout for the SDL2 host in"
        " host/donut_host.c: F begins a frame, P x1 y1 x2 y2 x3 y3 x4 y4 r g b"
        " emits a quad, and S presents the frame.)"
    )
    sent(
        'Import the C function printf taking a pointer to character and variadic'
        ' parameters, returning an integer, from the header "stdio.h".'
    )
    sent("(The torus: major radius %s, tube radius %s, a %d by %d grid of quads,"
         " spinning %s radians per frame and tilted %s radians.)"
         % (num(R), num(TUBE), RING, TUBE_N, num(SPIN_STEP), num(TILT)))
    sent("(Projection: centre (%s, %s), scale %s per world unit; light and"
         " shading follow the reference donut engine.)"
         % (num(OX), num(OY), num(SCALE)))
    if frames is None:
        sent("(This variant animates forever; stop it with Ctrl-C or the host's"
             " window close.)")
    else:
        sent("(A finite %d-frame variant used by the golden pipeline.)" % frames)

    sent("Set A to 0.0.")
    if frames is None:
        sent("While true:")
    else:
        sent("For f from 1 to %d:" % frames)

    sent("Add %s to A." % num(SPIN_STEP))
    sent("Set ca to cosine of A.")
    sent("Set sa to sine of A.")
    sent('Call printf with "F\\n" done.')
    sent("For i from 0 to %d:" % (RING - 1))
    sent("Set th1 to i times %s." % num(TH_STEP))
    sent("Set th2 to th1 plus %s." % num(TH_STEP))
    sent("Set ct1 to cosine of th1.")
    sent("Set st1 to sine of th1.")
    sent("Set ct2 to cosine of th2.")
    sent("Set st2 to sine of th2.")
    sent("For j from 0 to %d:" % (TUBE_N - 1))
    sent("Set ph1 to j times %s." % num(PH_STEP))
    sent("Set ph2 to ph1 plus %s." % num(PH_STEP))
    sent("Set cp1 to cosine of ph1.")
    sent("Set sp1 to sine of ph1.")
    sent("Set cp2 to cosine of ph2.")
    sent("Set sp2 to sine of ph2.")
    # Spin-rotated surface normal at (ph1, th1), then flat shading.
    sent("Set ny to sp1 times ca minus cp1 times sa.")
    sent("Set nz to sp1 times sa plus cp1 times ca.")
    sent("Set nx to cp1 times ct1 times %s plus nz times %s." % (num(CB), num(SB)))
    sent(
        "Set lum to (nx times %s plus ny times %s plus nz times %s plus 1) times 0.5."
        % (num(LIGHT[0]), num(LIGHT[1]), num(LIGHT[2]))
    )
    sent("Set cr to lum times 150 plus 80.")
    sent("Set cg to lum times 90 plus 50.")
    sent("Set cbl to lum times 60 plus 30.")
    sent('Call printf with "P\\n" done.')
    for cp, sp, ct, st in ((("cp1"), "sp1", "ct1", "st1"),
                           ("cp2", "sp1", "ct1", "st1"),
                           ("cp2", "sp1", "ct2", "st2"),
                           ("cp1", "sp1", "ct2", "st2")):
        sent("Set rad to %s plus %s times %s." % (num(R), num(TUBE), cp))
        sent("Set wx to rad times %s." % ct)
        sent("Set wy to %s times %s." % (num(TUBE), sp))
        sent("Set wz to rad times %s." % st)
        sent("Set ry to wy times ca minus wz times sa.")
        sent("Set rz to wy times sa plus wz times ca.")
        sent(
            "Set px to %s plus (wx times %s plus rz times %s) times %s."
            % (num(OX), num(CB), num(SB), num(SCALE))
        )
        sent("Set py to %s minus ry times %s." % (num(OY), num(SCALE)))
        sent('Call printf with "%f %f ", px, py done.')
    sent('Call printf with "%f %f %f\\n", cr, cg, cbl done.')
    sent("End for.")
    sent("End for.")
    sent('Call printf with "S\\n" done.')
    if frames is None:
        sent("End while.")
    else:
        sent("End for.")

    return "\n".join(L) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--frames",
        type=int,
        default=None,
        help="emit a finite N-frame program instead of the infinite animation",
    )
    args = parser.parse_args()

    infinite = ROOT / "examples" / "donut_engine.eng"
    finite = ROOT / "examples" / "donut_engine_finite.eng"

    text = generate(None)
    infinite.write_text(text, encoding="utf-8")
    print("wrote {}: {} sentences".format(infinite.name, text.count(".")))

    text = generate(3)
    finite.write_text(text, encoding="utf-8")
    print("wrote {}: {} sentences".format(finite.name, text.count(".")))

    golden = ROOT / "tests" / "golden" / "donut_engine_finite.eng"
    golden.write_text(text, encoding="utf-8")
    print("wrote {}: identical finite variant gating the golden pipeline".format(golden))


if __name__ == "__main__":
    main()
