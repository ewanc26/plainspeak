#!/usr/bin/env python3
"""Generate the PlainSpeak polygonal spinning donut engine.

The generated program computes an animated torus in native PlainSpeak prose
(loops, variables, and the built-in "sine of" / "cosine of" forms) and streams
the donut_host token protocol to stdout through the imported C printf:

    F                          begin frame
    P                          quad marker, followed by eleven numbers
    x1 y1 x2 y2 x3 y3 x4 y4 r g b   (one value per line, printf "%g\\n")
    S                          swap/present

The torus is harmonised with the sigi reference engine
(sigi/scripts/gen_donut_engine.py): same grid, spin step, tilt, projection and
shading, the same arithmetic order (accumulated loop counters, identical
expression trees), and the same "%g\\n" number formatting. The two engines'
streams are byte-identical frame for frame; scripts/check_donut_canonical.py
enforces that against a vendored canonical fixture.

Run:

    python3 scripts/gen_donut_engine.py                 # examples/donut_engine.eng (infinite)
    python3 scripts/gen_donut_engine.py --frames 8     # finite N-frame variant

Then:

    ./build/plainspeak examples/donut_engine.eng -o /tmp/donut
    /tmp/donut | ./host/donut_host
"""

import argparse
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Constructors of the canonical (sigi) engine. The ring loop ranges over 16
# radians in TH_STEP increments and the tube loop over 10 radians in PH_STEP
# increments, which yields 41 x 16 = 656 quads per frame.
R, TUBE = 3.0, 1.25
RING, TUBE_N = 16.0, 10.0
SCALE, OX, OY = 28.0, 120.0, 120.0
SPIN_STEP = 0.05
TILT = 0.72
LIGHT = (0.32, 0.58, 0.75)
TH_STEP = 2 * math.pi / RING
PH_STEP = 2 * math.pi / TUBE_N
CB, SB = round(math.cos(TILT), 12), round(math.sin(TILT), 12)
FINITE_FRAMES = 8


def num(v):
    # Match the canonical engine exactly: sigic reprints numeric literals in
    # generated C with printf("%g"), so its program effectively runs on the
    # 6-significant-digit forms (0.628319, 0.751806, ...). Emitting the same
    # shortest/%g literals here keeps the two streams bit-identical.
    return "{:g}".format(float(v))


def generate(frames):
    L = []

    def sent(text):
        L.append(text)

    sent("(A live polygonal spinning torus, written in native PlainSpeak.)")
    sent("(Generated by scripts/gen_donut_engine.py; do not edit by hand.)")
    sent(
        "(It streams the donut_host token protocol on stdout — F begins a"
        " frame, P followed by eleven numbers describes a quad, and S presents"
        " the frame — and is harmonised with sigi's canonical donut engine:"
        " same grid, spin, tilt, projection, shading, arithmetic order, and"
        ' printf "%g\\n" number formatting, so the two engines produce'
        " byte-identical streams frame for frame.)"
    )
    sent(
        'Import the C function printf taking a pointer to character and variadic'
        ' parameters, returning an integer, from the header "stdio.h".'
    )
    sent("(The torus: major radius %s, tube radius %s; the ring loop sweeps %d"
         " radians in %s steps and the tube loop sweeps %d radians in %s"
         " steps, giving %d by %d = %d shaded quads per frame, spinning %s"
         " radians per frame and tilted %s radians.)"
         % (num(R), num(TUBE), RING, num(TH_STEP), TUBE_N, num(PH_STEP),
            41, 16, 41 * 16, num(SPIN_STEP), num(TILT)))
    sent("(Projection: centre (%s, %s), scale %s per world unit; light and"
         " shading follow the reference donut engine.)"
         % (num(OX), num(OY), num(SCALE)))
    if frames is None:
        sent("(This variant animates forever; stop it with Ctrl-C or the host's"
             " window close.)")
    else:
        sent("(A finite %d-frame prefix of the same animation, used by the"
             " golden and canonical-parity pipelines.)" % frames)

    sent("Set A to 0.0.")
    if frames is None:
        sent("While true:")
    else:
        sent("For f from 1 to %d:" % frames)

    sent("Add %s to A." % num(SPIN_STEP))
    sent("Set ca to cosine of A.")
    sent("Set sa to sine of A.")
    sent('Call printf with "F\\n" done.')
    # The ring and tube loop counters accumulate by their step, exactly like
    # the sigi reference engine, so every intermediate value is bit-identical.
    sent("Set i to 0.0.")
    sent("While i is less than %d:" % RING)
    sent("Set th1 to i.")
    sent("Set th2 to th1 plus %s." % num(TH_STEP))
    sent("Set ct1 to cosine of th1.")
    sent("Set st1 to sine of th1.")
    sent("Set ct2 to cosine of th2.")
    sent("Set st2 to sine of th2.")
    sent("Set j to 0.0.")
    sent("While j is less than %d:" % TUBE_N)
    sent("Set ph1 to j.")
    sent("Set ph2 to ph1 plus %s." % num(PH_STEP))
    sent("Set cp1 to cosine of ph1.")
    sent("Set sp1 to sine of ph1.")
    sent("Set cp2 to cosine of ph2.")
    sent("Set sp2 to sine of ph2.")
    # Spin-rotated surface normal at (ph1, th1), then flat shading.
    sent("Set ny to sp1 times ca minus cp1 times st1 times sa.")
    sent("Set nz to sp1 times sa plus cp1 times st1 times ca.")
    sent("Set nx to cp1 times ct1 times %s plus nz times %s." % (num(CB), num(SB)))
    sent(
        "Set lum to (nx times %s plus ny times %s plus nz times %s plus 1) times 0.5."
        % (num(LIGHT[0]), num(LIGHT[1]), num(LIGHT[2]))
    )
    sent("Set cr to lum times 150 plus 80.")
    sent("Set cg to lum times 90 plus 50.")
    sent("Set cbl to lum times 60 plus 30.")
    sent('Call printf with "P\\n" done.')
    for cp, sp, ct, st in (("cp1", "sp1", "ct1", "st1"),
                           ("cp2", "sp1", "ct1", "st1"),
                           ("cp2", "sp1", "ct2", "st2"),
                           ("cp1", "sp1", "ct2", "st2")):
        sent("Set rad to %s times %s plus %s." % (cp, num(TUBE), num(R)))
        sent("Set wx to rad times %s." % ct)
        sent("Set wy to %s times %s." % (sp, num(TUBE)))
        sent("Set wz to rad times %s." % st)
        sent("Set ry to wy times ca minus wz times sa.")
        sent("Set rz to wy times sa plus wz times ca.")
        sent(
            "Set px to %s plus (wx times %s plus rz times %s) times %s."
            % (num(OX), num(CB), num(SB), num(SCALE))
        )
        sent("Set py to %s minus ry times %s." % (num(OY), num(SCALE)))
        sent('Call printf with "%g\\n", px done.')
        sent('Call printf with "%g\\n", py done.')
    sent('Call printf with "%g\\n", cr done.')
    sent('Call printf with "%g\\n", cg done.')
    sent('Call printf with "%g\\n", cbl done.')
    sent("Add %s to j." % num(PH_STEP))
    sent("End while.")
    sent("Add %s to i." % num(TH_STEP))
    sent("End while.")
    sent('Call printf with "S\\n" done.')
    if frames is None:
        sent("End while.")
    else:
        sent("End for.")

    return "\n".join(L) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--frames",
        type=int,
        default=None,
        help="emit a finite N-frame program instead of the infinite animation",
    )
    args = parser.parse_args()

    text = generate(None)
    infinite = ROOT / "examples" / "donut_engine.eng"
    infinite.write_text(text, encoding="utf-8")
    print("wrote {}: {} sentences".format(infinite.name, text.count(".")))

    text = generate(FINITE_FRAMES)
    finite = ROOT / "examples" / "donut_engine_finite.eng"
    finite.write_text(text, encoding="utf-8")
    print("wrote {}: {} sentences".format(finite.name, text.count(".")))

    golden = ROOT / "tests" / "golden" / "donut_engine_finite.eng"
    golden.write_text(text, encoding="utf-8")
    print("wrote {}: identical finite variant gating the golden pipeline".format(golden))


if __name__ == "__main__":
    main()
